import { useState } from "react";
import {
  Alert,
  Box,
  Button,
  Card,
  CardContent,
  CardHeader,
  Chip,
  Divider,
  Grid,
  IconButton,
  LinearProgress,
  MenuItem,
  Skeleton,
  Stack,
  TextField,
  Tooltip,
  Typography,
} from "@mui/material";
import DeleteOutline from "@mui/icons-material/DeleteOutline";
import PageHeader from "../components/PageHeader";
import ConfirmDialog from "../components/ConfirmDialog";
import useApi from "../hooks/useApi";
import { useToast } from "../context/ToastContext";
import { interviewsApi, jobsApi } from "../services/endpoints";
import { errorMessage, formatDateTime, scoreColor } from "../utils/format";

const KINDS = [
  { value: "mixed", label: "Mixed (technical + HR)" },
  { value: "technical", label: "Technical" },
  { value: "hr", label: "HR / behavioral" },
];

function Evaluation({ evaluation }) {
  return (
    <Stack spacing={1.5} sx={{ mt: 2 }}>
      <Stack direction="row" spacing={1} alignItems="center">
        <Chip color={scoreColor(evaluation.score * 10)} label={`Score ${evaluation.score}/10`} />
        <Typography variant="caption" color="text.secondary">
          {evaluation.answer_word_count} words
        </Typography>
      </Stack>
      {(evaluation.notes || []).map((note) => (
        <Alert key={note} severity="info">{note}</Alert>
      ))}
      {evaluation.strengths?.length > 0 && (
        <Box>
          <Typography variant="subtitle2" color="success.main">What worked</Typography>
          {evaluation.strengths.map((s) => (
            <Typography key={s} variant="body2">• {s}</Typography>
          ))}
        </Box>
      )}
      {evaluation.improvements?.length > 0 && (
        <Box>
          <Typography variant="subtitle2" color="warning.main">How to improve</Typography>
          {evaluation.improvements.map((s) => (
            <Typography key={s} variant="body2">• {s}</Typography>
          ))}
        </Box>
      )}
      {evaluation.sample_answer_outline && (
        <Box>
          <Typography variant="subtitle2">A strong answer would cover</Typography>
          <Typography variant="body2" sx={{ whiteSpace: "pre-wrap" }}>{evaluation.sample_answer_outline}</Typography>
        </Box>
      )}
    </Stack>
  );
}

function StartForm({ onStarted }) {
  const toast = useToast();
  const jobs = useApi(() => jobsApi.list({ limit: 100 }), []);
  const jobList = jobs.data?.jobs || jobs.data?.items || [];
  const [form, setForm] = useState({ role: "", job_id: "", kind: "mixed", count: 5, difficulty: "medium" });
  const [busy, setBusy] = useState(false);
  const set = (key) => (e) => setForm((f) => ({ ...f, [key]: e.target.value }));

  const start = async (event) => {
    event.preventDefault();
    setBusy(true);
    try {
      const body = { kind: form.kind, count: Number(form.count), difficulty: form.difficulty };
      if (form.role.trim()) body.role = form.role.trim();
      if (form.job_id) body.job_id = form.job_id;
      const session = await interviewsApi.createSession(body);
      toast.success("Questions ready");
      onStarted(session);
    } catch (err) {
      toast.error(errorMessage(err, "Could not create the session"));
    } finally {
      setBusy(false);
    }
  };

  return (
    <Card>
      <CardHeader title="Start a practice interview" subheader="Questions are generated by your local model from the role and, optionally, a saved job." />
      <CardContent sx={{ pt: 0 }}>
        <form onSubmit={start}>
          <Stack spacing={2}>
            <TextField size="small" label="Role (optional if you pick a job)" value={form.role} onChange={set("role")} inputProps={{ maxLength: 100 }} />
            <TextField select size="small" label="Saved job (optional)" value={form.job_id} onChange={set("job_id")}>
              <MenuItem value="">None</MenuItem>
              {jobList.map((job) => (
                <MenuItem key={job.id} value={job.id}>{job.title} - {job.company}</MenuItem>
              ))}
            </TextField>
            <TextField select size="small" label="Type" value={form.kind} onChange={set("kind")}>
              {KINDS.map((k) => <MenuItem key={k.value} value={k.value}>{k.label}</MenuItem>)}
            </TextField>
            <Stack direction="row" spacing={2}>
              <TextField select size="small" fullWidth label="Questions" value={form.count} onChange={set("count")}>
                {[3, 5, 7, 10].map((n) => <MenuItem key={n} value={n}>{n}</MenuItem>)}
              </TextField>
              <TextField select size="small" fullWidth label="Difficulty" value={form.difficulty} onChange={set("difficulty")}>
                {["easy", "medium", "hard"].map((d) => <MenuItem key={d} value={d}>{d}</MenuItem>)}
              </TextField>
            </Stack>
            {busy && (
              <Box>
                <LinearProgress />
                <Typography variant="caption" color="text.secondary">Generating questions locally. This can take a minute or two.</Typography>
              </Box>
            )}
            <Box>
              <Button type="submit" variant="contained" disabled={busy}>{busy ? "Generating..." : "Start practice"}</Button>
            </Box>
          </Stack>
        </form>
      </CardContent>
    </Card>
  );
}

function SessionList({ sessions, activeId, onOpen, onDelete }) {
  return (
    <Card sx={{ mt: 3 }}>
      <CardHeader title="Your sessions" />
      <CardContent sx={{ pt: 0 }}>
        {sessions.loading && !sessions.data ? (
          <Skeleton variant="rounded" height={60} />
        ) : sessions.error ? (
          <Alert severity="error">{sessions.error}</Alert>
        ) : (sessions.data?.sessions || []).length === 0 ? (
          <Typography color="text.secondary">No sessions yet. Start one above.</Typography>
        ) : (
          <Stack spacing={1}>
            {sessions.data.sessions.map((s) => (
              <Stack
                key={s.id}
                direction="row"
                alignItems="center"
                spacing={1}
                onClick={() => onOpen(s.id)}
                sx={{ p: 1.25, border: 1, borderColor: s.id === activeId ? "primary.main" : "divider", borderRadius: 2, cursor: "pointer" }}
              >
                <Box sx={{ flexGrow: 1, minWidth: 0 }}>
                  <Typography variant="body2" fontWeight={600} noWrap>{s.title}</Typography>
                  <Typography variant="caption" color="text.secondary">
                    {formatDateTime(s.created_at)} · {s.progress.answered}/{s.progress.total} answered
                  </Typography>
                </Box>
                {s.overall_score != null ? (
                  <Chip size="small" color={scoreColor(s.overall_score * 10)} label={`${s.overall_score}/10`} />
                ) : (
                  <Chip size="small" variant="outlined" label="In progress" />
                )}
                <Tooltip title="Delete">
                  <IconButton size="small" color="error" aria-label="Delete session" onClick={(e) => { e.stopPropagation(); onDelete(s); }}>
                    <DeleteOutline fontSize="small" />
                  </IconButton>
                </Tooltip>
              </Stack>
            ))}
          </Stack>
        )}
      </CardContent>
    </Card>
  );
}

function SessionView({ session, onChanged }) {
  const toast = useToast();
  const [viewIndex, setViewIndex] = useState(session.next_index ?? 0);
  const [answer, setAnswer] = useState("");
  const [busy, setBusy] = useState(false);
  const [finishing, setFinishing] = useState(false);
  const [summary, setSummary] = useState(null);

  const question = session.questions[viewIndex];
  const completed = session.status === "completed";
  const allAnswered = session.progress.answered === session.progress.total;

  const submit = async () => {
    setBusy(true);
    try {
      await interviewsApi.answer(session.id, { index: viewIndex, answer: answer.trim() });
      setAnswer("");
      await onChanged();
    } catch (err) {
      toast.error(errorMessage(err, "Could not evaluate the answer"));
    } finally {
      setBusy(false);
    }
  };

  const finish = async () => {
    setFinishing(true);
    try {
      const res = await interviewsApi.complete(session.id);
      setSummary(res);
      await onChanged();
    } catch (err) {
      toast.error(errorMessage(err));
    } finally {
      setFinishing(false);
    }
  };

  return (
    <Card>
      <CardHeader
        title={session.title}
        subheader={`${session.difficulty} · ${session.progress.answered}/${session.progress.total} answered${session.company ? ` · ${session.company}` : ""}`}
        action={completed && session.overall_score != null ? <Chip color={scoreColor(session.overall_score * 10)} label={`Overall ${session.overall_score}/10`} /> : null}
      />
      <CardContent sx={{ pt: 0 }}>
        <Stack direction="row" spacing={0.75} sx={{ mb: 2, flexWrap: "wrap" }}>
          {session.questions.map((q, i) => (
            <Chip
              key={q.index}
              size="small"
              label={i + 1}
              color={q.evaluation ? scoreColor(q.evaluation.score * 10) : "default"}
              variant={i === viewIndex ? "filled" : "outlined"}
              onClick={() => setViewIndex(i)}
            />
          ))}
        </Stack>

        {question && (
          <Box>
            <Stack direction="row" spacing={1} sx={{ mb: 1 }}>
              <Chip size="small" label={question.category} />
              {question.focus_skill && <Chip size="small" variant="outlined" label={question.focus_skill} />}
            </Stack>
            <Typography variant="h6" sx={{ mb: 2 }}>{question.question}</Typography>

            {question.evaluation ? (
              <>
                <Typography variant="subtitle2" color="text.secondary">Your answer</Typography>
                <Typography variant="body2" sx={{ whiteSpace: "pre-wrap" }}>{question.answer}</Typography>
                <Evaluation evaluation={question.evaluation} />
              </>
            ) : completed ? (
              <Typography color="text.secondary">This question was not answered.</Typography>
            ) : (
              <Stack spacing={1.5}>
                <TextField
                  multiline
                  minRows={5}
                  maxRows={14}
                  label="Your answer"
                  value={answer}
                  onChange={(e) => setAnswer(e.target.value)}
                  inputProps={{ maxLength: 4000 }}
                  helperText="Answer as you would in the interview. A structured answer with an example scores best."
                />
                {busy && (
                  <Box>
                    <LinearProgress />
                    <Typography variant="caption" color="text.secondary">Evaluating locally. This can take a minute.</Typography>
                  </Box>
                )}
                <Box>
                  <Button variant="contained" onClick={submit} disabled={busy || !answer.trim()}>
                    {busy ? "Evaluating..." : "Submit answer"}
                  </Button>
                </Box>
              </Stack>
            )}
          </Box>
        )}

        <Divider sx={{ my: 2 }} />
        <Stack direction="row" spacing={1} alignItems="center" sx={{ flexWrap: "wrap" }}>
          {viewIndex > 0 && <Button size="small" onClick={() => setViewIndex(viewIndex - 1)}>Previous</Button>}
          {viewIndex < session.questions.length - 1 && <Button size="small" onClick={() => setViewIndex(viewIndex + 1)}>Next question</Button>}
          <Box sx={{ flexGrow: 1 }} />
          {!completed && (
            <Button variant={allAnswered ? "contained" : "outlined"} size="small" onClick={finish} disabled={finishing || session.progress.answered === 0}>
              {finishing ? "Finishing..." : "Finish and get feedback"}
            </Button>
          )}
        </Stack>

        {summary && (
          <Alert severity="success" sx={{ mt: 2 }}>
            <Typography variant="subtitle2">Session complete: overall {summary.feedback.overall_score}/10</Typography>
            {Object.entries(summary.feedback.category_scores || {}).map(([cat, score]) => (
              <Typography key={cat} variant="body2">{cat}: {score}/10</Typography>
            ))}
            {summary.feedback.improvements?.slice(0, 4).map((s) => (
              <Typography key={s} variant="body2">• {s}</Typography>
            ))}
            {summary.skill_updates?.length > 0 && (
              <Typography variant="caption" display="block" sx={{ mt: 1 }}>
                Skills updated from this practice: {summary.skill_updates.map((u) => `${u.skill} (${u.kind})`).join(", ")}
              </Typography>
            )}
          </Alert>
        )}
      </CardContent>
    </Card>
  );
}

export default function InterviewLab() {
  const toast = useToast();
  const sessions = useApi(() => interviewsApi.sessions(), []);
  const [activeId, setActiveId] = useState(null);
  const [session, setSession] = useState(null);
  const [toDelete, setToDelete] = useState(null);
  const [deleting, setDeleting] = useState(false);

  const open = async (id) => {
    try {
      setSession(await interviewsApi.getSession(id));
      setActiveId(id);
    } catch (err) {
      toast.error(errorMessage(err));
    }
  };

  const refresh = async () => {
    if (activeId) setSession(await interviewsApi.getSession(activeId));
    sessions.reload();
  };

  const remove = async () => {
    setDeleting(true);
    try {
      await interviewsApi.removeSession(toDelete.id);
      if (toDelete.id === activeId) {
        setActiveId(null);
        setSession(null);
      }
      toast.success("Session deleted");
      setToDelete(null);
      sessions.reload();
    } catch (err) {
      toast.error(errorMessage(err));
    } finally {
      setDeleting(false);
    }
  };

  return (
    <>
      <PageHeader
        title="Interview Lab"
        subtitle="Practise technical and HR questions with feedback on every answer. Everything runs on your local model."
      />
      <Grid container spacing={2.5}>
        <Grid item xs={12} lg={5}>
          <StartForm
            onStarted={(created) => {
              setSession(created);
              setActiveId(created.id);
              sessions.reload();
            }}
          />
          <SessionList sessions={sessions} activeId={activeId} onOpen={open} onDelete={setToDelete} />
        </Grid>
        <Grid item xs={12} lg={7}>
          {session ? (
            <SessionView key={session.id} session={session} onChanged={refresh} />
          ) : (
            <Card>
              <CardContent>
                <Typography color="text.secondary">
                  Start a practice interview or open a previous session. Each answer is scored from 0 to 10 with specific strengths and improvements.
                </Typography>
              </CardContent>
            </Card>
          )}
        </Grid>
      </Grid>

      <ConfirmDialog
        open={Boolean(toDelete)}
        title="Delete this session?"
        message="The session and its feedback will be removed."
        confirmLabel="Delete"
        loading={deleting}
        onConfirm={remove}
        onClose={() => setToDelete(null)}
      />
    </>
  );
}
