"""Recruiter messages with a human approval gate.

Lifecycle:  draft  ->  approved  ->  sent

- Drafts are generated by the Recruiter Outreach agent and can be freely edited.
- Approving requires an explicit confirmation. The approval is bound to the exact text (a SHA-256 hash).
  Editing an approved message clears the approval, so what you approved is always what you send.
- Kithi never sends anything. After approval it can build a mailto: link that opens YOUR email app with
  the text filled in; "sent" only records that you sent it yourself. Messages cannot be marked sent
  unless they were approved and are unchanged since.
- Content from job postings and received messages is untrusted and can never approve or send anything.
"""
import hashlib
import re
from urllib.parse import quote

from fastapi import APIRouter, Depends, HTTPException, Query, Request

from app.agents.recruiter_outreach import generate_message
from app.api.deps import get_current_user
from app.core.prompt_guard import sanitize_untrusted
from app.database.mongo import get_db
from app.schemas.recruiter import MESSAGE_STATUSES, ApprovalIn, MessageGenerateIn, MessageUpdate, SentIn
from app.services.audit import log_activity
from app.services.candidate import load_candidate_context
from app.services.matching import get_weights
from app.services.tasks import record_task
from app.utils.helpers import clamp_limit, get_owned_or_404, public, utcnow

router = APIRouter(prefix="/recruiter-messages", tags=["recruiter-messages"])

MAX_MESSAGES = 500
HISTORY_LIMIT = 50
MAILTO_SOFT_LIMIT = 1800
_PLACEHOLDER = re.compile(r"\[[^\]\n]{1,60}\](?!\()|\bTODO\b|\{\{.*?\}\}", re.I)
_CTRL = re.compile(r"[\x00-\x1f\x7f]")


def _hash(doc: dict) -> str:
    material = f"{doc['channel']}\n{doc.get('subject', '')}\n{doc['body']}"
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


def _entry(status: str, note: str | None) -> dict:
    return {"status": status, "at": utcnow(), "note": (note or "").strip()[:300]}


def _owned_or_422(collection: str, value: str | None, user_id, label: str) -> dict | None:
    if not value:
        return None
    try:
        return get_owned_or_404(collection, value, user_id)
    except HTTPException:
        raise HTTPException(status_code=422, detail=f"The selected {label} was not found")


def _out(doc: dict, *drop: str) -> dict:
    out = public(doc, *drop)
    out["sendable"] = doc["status"] == "approved"
    return out


@router.post("/generate", status_code=201)
def generate(body: MessageGenerateIn, request: Request, user: dict = Depends(get_current_user)) -> dict:
    """Draft a message. The result is always a draft: nothing is approved or sent."""
    db = get_db()
    if db.recruiter_messages.count_documents({"user_id": user["_id"]}) >= MAX_MESSAGES:
        raise HTTPException(status_code=409, detail=f"You have reached the limit of {MAX_MESSAGES} messages. Delete some first.")

    recruiter = _owned_or_422("recruiters", body.recruiter_id, user["_id"], "recruiter")
    application = _owned_or_422("applications", body.application_id, user["_id"], "application")
    job_id = body.job_id or (str(application["job_id"]) if application and application.get("job_id") else None)
    job = _owned_or_422("jobs", job_id, user["_id"], "job")

    ctx = load_candidate_context(user["_id"], user)
    if not ctx["has_data"]:
        raise HTTPException(status_code=422, detail="Upload a resume or complete your candidate profile before drafting messages.")

    result = generate_message(
        ctx, body.kind, body.channel, body.tone, get_weights(user),
        recruiter=recruiter, job=job, application=application,
        incoming_message=body.incoming_message, note=body.note,
    )
    now = utcnow()
    doc = {
        "user_id": user["_id"],
        "kind": body.kind,
        "channel": body.channel,
        "tone": body.tone,
        "recruiter_id": recruiter["_id"] if recruiter else None,
        "recruiter_name": recruiter.get("name") if recruiter else None,
        "job_id": job["_id"] if job else None,
        "application_id": application["_id"] if application else None,
        "company": (job or application or recruiter or {}).get("company"),
        "subject": result["subject"],
        "body": result["body"],
        "status": "draft",
        "source": result["source"],  # "ai" = model-written and fact-checked, "template" = verified-facts template
        "ai_error": result["ai_error"],
        "warnings": result["warnings"],
        "removed_sentences": result["removed_sentences"][:20],
        "injection_flags": result["injection_flags"],
        "edited": False,
        "approved_hash": None,
        "approved_at": None,
        "sent_at": None,
        "history": [_entry("draft", "Drafted")],
        "created_at": now,
        "updated_at": now,
    }
    doc["_id"] = db.recruiter_messages.insert_one(doc).inserted_id
    record_task(
        user["_id"], "recruiter_outreach", "completed" if result["source"] == "ai" else "partial",
        f"Drafted {body.kind} message", {"message_id": str(doc["_id"]), "channel": body.channel},
    )
    log_activity(user["_id"], "recruiter_message.drafted", {"message_id": str(doc["_id"]), "kind": body.kind}, request)
    return {"message": _out(doc)}


@router.get("")
def list_messages(
    status: str | None = Query(default=None, max_length=20),
    kind: str | None = Query(default=None, max_length=20),
    recruiter_id: str | None = Query(default=None, max_length=24),
    limit: int = Query(default=100),
    user: dict = Depends(get_current_user),
) -> dict:
    query: dict = {"user_id": user["_id"]}
    if status:
        if status not in MESSAGE_STATUSES:
            raise HTTPException(status_code=422, detail="Unknown status")
        query["status"] = status
    if kind:
        query["kind"] = kind
    if recruiter_id:
        query["recruiter_id"] = get_owned_or_404("recruiters", recruiter_id, user["_id"], {"_id": 1})["_id"]
    db = get_db()
    docs = db.recruiter_messages.find(query, {"removed_sentences": 0, "history": 0}).sort("updated_at", -1).limit(clamp_limit(limit, 500))
    return {"total": db.recruiter_messages.count_documents(query), "items": [_out(d) for d in docs]}


@router.get("/{message_id}")
def get_message(message_id: str, user: dict = Depends(get_current_user)) -> dict:
    return _out(get_owned_or_404("recruiter_messages", message_id, user["_id"]))


@router.put("/{message_id}")
def edit_message(message_id: str, body: MessageUpdate, request: Request, user: dict = Depends(get_current_user)) -> dict:
    """Edit a draft. Editing an approved message clears its approval; a sent message cannot be edited."""
    db = get_db()
    doc = get_owned_or_404("recruiter_messages", message_id, user["_id"])
    if doc["status"] == "sent":
        raise HTTPException(status_code=409, detail="A sent message cannot be edited. Draft a new one instead.")

    updates: dict = {}
    if body.subject is not None:
        updates["subject"] = _CTRL.sub(" ", sanitize_untrusted(body.subject, 200)).strip()
    if body.body is not None:
        text = sanitize_untrusted(body.body, 8000).strip()
        if not text:
            raise HTTPException(status_code=422, detail="The message must not be blank")
        updates["body"] = text
    updates["edited"] = True
    updates["updated_at"] = utcnow()

    op: dict = {"$set": updates}
    if doc["status"] == "approved":
        updates.update(status="draft", approved_hash=None, approved_at=None)
        op["$push"] = {"history": {"$each": [_entry("draft", "Edited after approval; approval cleared")], "$slice": -HISTORY_LIMIT}}
    db.recruiter_messages.update_one({"_id": doc["_id"], "user_id": user["_id"]}, op)
    log_activity(user["_id"], "recruiter_message.edited", {"message_id": message_id}, request)
    return _out(db.recruiter_messages.find_one({"_id": doc["_id"]}))


@router.post("/{message_id}/approve")
def approve(message_id: str, body: ApprovalIn, request: Request, user: dict = Depends(get_current_user)) -> dict:
    """Approve the exact current text. Required before the message can be opened in your email app or marked sent."""
    db = get_db()
    doc = get_owned_or_404("recruiter_messages", message_id, user["_id"])
    if doc["status"] != "draft":
        raise HTTPException(status_code=409, detail=f"Only drafts can be approved. This message is {doc['status']}.")
    if doc["channel"] == "email" and not (doc.get("subject") or "").strip():
        raise HTTPException(status_code=422, detail="Add a subject line before approving an email.")
    if _PLACEHOLDER.search(doc["body"]) or _PLACEHOLDER.search(doc.get("subject") or ""):
        raise HTTPException(status_code=422, detail="Replace the placeholder text (such as [brackets] or TODO) before approving.")

    now = utcnow()
    db.recruiter_messages.update_one(
        {"_id": doc["_id"], "user_id": user["_id"]},
        {
            "$set": {"status": "approved", "approved_hash": _hash(doc), "approved_at": now, "updated_at": now},
            "$push": {"history": {"$each": [_entry("approved", "Approved by you")], "$slice": -HISTORY_LIMIT}},
        },
    )
    log_activity(user["_id"], "recruiter_message.approved", {"message_id": message_id}, request)
    return _out(db.recruiter_messages.find_one({"_id": doc["_id"]}))


@router.get("/{message_id}/mailto")
def mailto(message_id: str, user: dict = Depends(get_current_user)) -> dict:
    """A mailto: link that opens YOUR email app with the approved text. Kithi does not send the email."""
    doc = get_owned_or_404("recruiter_messages", message_id, user["_id"])
    if doc["status"] != "approved" or doc.get("approved_hash") != _hash(doc):
        raise HTTPException(status_code=409, detail="Approve the message first. Approval is required before it can be opened for sending.")
    if doc["channel"] != "email":
        raise HTTPException(status_code=422, detail="This is a LinkedIn message. Copy the text and paste it into LinkedIn yourself.")
    recruiter = (
        get_db().recruiters.find_one({"_id": doc["recruiter_id"], "user_id": user["_id"]}) if doc.get("recruiter_id") else None
    )
    email = ((recruiter or {}).get("email") or "").strip()
    if not email or _CTRL.search(email):
        raise HTTPException(status_code=422, detail="This recruiter has no email address saved. Add one, or copy the text into your email app.")

    url = f"mailto:{quote(email, safe='@')}?subject={quote(doc.get('subject') or '', safe='')}&body={quote(doc['body'], safe='')}"
    return {
        "url": url,
        "to": email,
        "too_long": len(url) > MAILTO_SOFT_LIMIT,
        "note": "Some email apps cut off very long links. If the body looks shortened, copy the text instead.",
    }


@router.post("/{message_id}/mark-sent")
def mark_sent(message_id: str, body: SentIn, request: Request, user: dict = Depends(get_current_user)) -> dict:
    """Record that YOU sent the approved message. Only possible for an approved, unchanged message."""
    db = get_db()
    doc = get_owned_or_404("recruiter_messages", message_id, user["_id"])
    if doc["status"] != "approved" or doc.get("approved_hash") != _hash(doc):
        raise HTTPException(status_code=409, detail="Only an approved, unchanged message can be marked as sent. Approve it first.")
    now = utcnow()
    db.recruiter_messages.update_one(
        {"_id": doc["_id"], "user_id": user["_id"]},
        {
            "$set": {"status": "sent", "sent_at": now, "updated_at": now},
            "$push": {"history": {"$each": [_entry("sent", body.note or "Marked as sent by you")], "$slice": -HISTORY_LIMIT}},
        },
    )
    log_activity(user["_id"], "recruiter_message.sent", {"message_id": message_id}, request)
    return _out(db.recruiter_messages.find_one({"_id": doc["_id"]}))


@router.delete("/{message_id}", status_code=204)
def delete_message(message_id: str, request: Request, user: dict = Depends(get_current_user)) -> None:
    doc = get_owned_or_404("recruiter_messages", message_id, user["_id"], {"_id": 1})
    get_db().recruiter_messages.delete_one({"_id": doc["_id"], "user_id": user["_id"]})
    log_activity(user["_id"], "recruiter_message.deleted", {"message_id": message_id}, request)
